"use client";

import { useRouter } from "next/navigation";
import { ShieldAlert } from "lucide-react";
import type { FormEvent } from "react";
import { useWorkingContext } from "@/components/auth/session";
import { Page } from "@/components/layout/page-header";
import { FormError, Loaded } from "@/components/ui/api-states";
import { Button, ButtonLink } from "@/components/ui/button";
import { Field, Input, Textarea } from "@/components/ui/form";
import { Alert } from "@/components/ui/misc";
import { useToast } from "@/components/ui/toast";
import { ACCESS_ALL_ORGANIZATIONS, orgApi, orgCan, OrgPermission, type OrganizationDto } from "@/lib/organizations";
import { useApiMutation, useApiQuery } from "@/lib/use-api";

const FIELDS = ["name", "code", "email", "phone", "address"] as const;
type FieldName = (typeof FIELDS)[number];
/** Fields the backend accepts as null; name and (on edit) code must have a value. */
const CLEARABLE = new Set<FieldName>(["email", "phone", "address"]);

/** POST /v1/organizations: platform administrators only. */
export function CreateOrganization() {
  const { ready, can } = useWorkingContext();
  return (
    <Page
      title="New organization"
      breadcrumbs={[{ label: "Organizations", href: "/organizations" }, { label: "New organization" }]}
    >
      {ready && !can(ACCESS_ALL_ORGANIZATIONS) ? (
        <Alert tone="warning" icon={ShieldAlert} title="Platform administrators only">
          Only a platform administrator can create an organization.
        </Alert>
      ) : (
        <OrganizationForm />
      )}
    </Page>
  );
}

/** PATCH /v1/organizations/:id: needs "manage organization" there. */
export function EditOrganization({ id }: { id: string }) {
  const organization = useApiQuery<OrganizationDto>(orgApi.one(id));
  const name = organization.data?.name ?? "Organization";
  return (
    <Page
      title={`Edit ${name}`}
      breadcrumbs={[
        { label: "Organizations", href: "/organizations" },
        { label: name, href: `/organizations/${id}` },
        { label: "Edit" },
      ]}
    >
      <Loaded query={organization}>
        {(data) =>
          orgCan(data, OrgPermission.Manage) ? (
            <OrganizationForm organization={data} />
          ) : (
            <Alert tone="warning" icon={ShieldAlert} title="You cannot edit this organization">
              Changing its details needs the “manage organization” permission.
            </Alert>
          )
        }
      </Loaded>
    </Page>
  );
}

function OrganizationForm({ organization }: { organization?: OrganizationDto }) {
  const router = useRouter();
  const toast = useToast();
  const save = useApiMutation();
  const editing = organization !== undefined;

  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const form = new FormData(event.currentTarget);
    const value = (name: FieldName) => String(form.get(name) ?? "").trim();

    let body: Partial<Record<FieldName, string | null>>;
    if (organization) {
      // PATCH changes only the fields sent.
      body = {};
      for (const field of FIELDS) {
        const next = value(field);
        if (next === (organization[field] ?? "")) continue;
        body[field] = next === "" && CLEARABLE.has(field) ? null : next;
      }
      if (Object.keys(body).length === 0) {
        router.push(`/organizations/${organization.id}`);
        return;
      }
    } else {
      // A blank code is generated by the backend.
      body = Object.fromEntries(FIELDS.map((field) => [field, value(field) || null]));
      body.name = value("name");
    }

    const sent = await save.send<OrganizationDto>(organization ? orgApi.one(organization.id) : orgApi.list, {
      method: organization ? "PATCH" : "POST",
      body,
    });
    if (!sent.ok) return;
    toast({ title: editing ? "Organization saved" : "Organization created", description: sent.data.name });
    router.push(`/organizations/${sent.data.id}`);
  }

  const errors = save.fieldErrors;

  return (
    <form onSubmit={submit} onChange={save.clear} className="grid max-w-3xl gap-6">
      <fieldset disabled={save.submitting} className="grid gap-5 sm:grid-cols-2">
        <legend className="sr-only">Organization details</legend>
        <Field label="Name" htmlFor="name" error={errors.name}>
          <Input id="name" name="name" defaultValue={organization?.name} required maxLength={100} placeholder="SPS Education System" />
        </Field>
        <Field
          label="Short code"
          htmlFor="code"
          error={errors.code}
          help={editing ? "Letters, numbers, dashes and underscores." : "Letters, numbers, dashes and underscores. Leave blank to generate one."}
        >
          <Input
            id="code"
            name="code"
            defaultValue={organization?.code}
            required={editing}
            maxLength={50}
            pattern="[A-Za-z0-9_\-]+"
            placeholder="SPS"
            className="font-mono"
          />
        </Field>
        <Field label="Email" htmlFor="email" error={errors.email}>
          <Input id="email" name="email" type="email" defaultValue={organization?.email ?? ""} maxLength={100} />
        </Field>
        <Field label="Phone" htmlFor="phone" error={errors.phone}>
          <Input id="phone" name="phone" type="tel" defaultValue={organization?.phone ?? ""} maxLength={50} />
        </Field>
        <Field label="Head office address" htmlFor="address" error={errors.address} className="sm:col-span-2">
          <Textarea id="address" name="address" defaultValue={organization?.address ?? ""} maxLength={1000} rows={3} />
        </Field>
      </fieldset>
      <FormError error={save.error} fields={FIELDS} />
      <div className="flex flex-wrap gap-2">
        <Button type="submit" disabled={save.submitting}>
          {save.submitting ? "Saving…" : editing ? "Save changes" : "Create organization"}
        </Button>
        <ButtonLink href={organization ? `/organizations/${organization.id}` : "/organizations"} variant="outline">
          Cancel
        </ButtonLink>
      </div>
    </form>
  );
}
